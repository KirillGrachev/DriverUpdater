/// <reference types="vitest/config" />
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import packageJson from './package.json';

// Tauri expects a fixed dev-server port on the loopback interface.
const TAURI_DEV_HOST = '127.0.0.1';
const TAURI_DEV_PORT = 5173;

export default defineConfig({
    plugins: [react()],
    define: {
        __APP_VERSION__: JSON.stringify(packageJson.version),
        __BUILD_DATE__: JSON.stringify(new Date().toISOString()),
    },
    clearScreen: false,
    server: {
        port: TAURI_DEV_PORT,
        strictPort: true,
        // Bind to loopback only: the dev server exposes raw sources and must not
        // be reachable from the local network.
        host: TAURI_DEV_HOST,
        allowedHosts: [TAURI_DEV_HOST, 'localhost'],
        watch: {
            // The Rust build directory lives inside the Vite root, so chokidar would
            // otherwise watch target/ recursively. On Windows cargo keeps linking
            // those .exe/.pdb files exclusively locked, and watching them fails the
            // whole dev server with EBUSY (Tauri then kills beforeDevCommand).
            // Nothing there is frontend source, so keep the watcher out of it.
            ignored: [
                // Rust build artifacts (cargo locks .exe/.pdb while linking).
                '**/src-tauri/target/**',
                // Schemas generated by tauri-build.
                '**/src-tauri/gen/**',
                // Our own build output.
                '**/dist/**',
                // Editor/atomic-write temp files (Windows keeps them briefly locked).
                '**/.*.tmpdir/**',
                '**/*.tmp',
                // Bundled font files and their license never change during dev.
                '**/assets/fonts/**',
                // Branding artwork is imported once and never edited by Vite.
                '**/assets/branding/**',
            ],
        },
    },
    envPrefix: ['VITE_', 'TAURI_ENV_'],
    build: {
        target: 'es2021',
        outDir: 'dist',
        // No source maps in shipped builds: they inflate the bundle and expose
        // the full source tree to anyone with the installer.
        sourcemap: false,
    },
    test: {
        environment: 'node',
        include: ['src/**/*.test.ts', 'src/**/*.test.tsx'],
    },
});
